def bootstrap_ci(data, func=np.mean, n_boot=CONFIG.bootstrap_repetitions, seed=CONFIG.random_seed, ci=95):
    """Calculates bootstrap confidence intervals for a given 1D array."""
    data = np.array(data)
    data = data[~np.isnan(data)]
    if len(data) < 2: return np.nan, np.nan
    rng = np.random.RandomState(seed)
    boot_stats = [func(rng.choice(data, size=len(data), replace=True)) for _ in range(n_boot)]
    lower = np.percentile(boot_stats, (100 - ci) / 2.0)
    upper = np.percentile(boot_stats, 100 - (100 - ci) / 2.0)
    return lower, upper

