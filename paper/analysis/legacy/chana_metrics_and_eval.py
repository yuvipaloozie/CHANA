def get_gradcam(img_tensor, model_instance):
    if isinstance(model_instance.output, list):
        out_tensor = next((o for o in model_instance.output if 'final' in o.name.lower()), model_instance.output[0])
    else: out_tensor = model_instance.output

    valid_layers = [l.name for l in model_instance.layers if isinstance(l, (tf.keras.layers.Conv2D, tf.keras.layers.Conv2DTranspose))]

    target_layer, saved_grads, saved_conv_outputs = None, None, None
    for layer_name in reversed(valid_layers):
        if any(x in layer_name.lower() for x in ['output', 'final', 'aux']): continue
        grad_model = Model(model_instance.inputs, [model_instance.get_layer(layer_name).output, out_tensor])
        with tf.GradientTape() as tape:
            conv_outputs, predictions = grad_model(img_tensor)
            loss = predictions[:, :, :, 0]
        grads = tape.gradient(loss, conv_outputs)
        if grads is not None:
            target_layer, saved_grads, saved_conv_outputs = layer_name, grads[0], conv_outputs[0]
            break

    if saved_grads is None: return np.zeros((512, 512))

    weights = tf.reduce_mean(saved_grads, axis=(0, 1))
    cam = tf.reduce_sum(tf.multiply(weights, saved_conv_outputs), axis=-1)
    cam = tf.maximum(cam, 0)
    cam_max = tf.reduce_max(cam)
    if cam_max > 0: cam = cam / cam_max
    return cv2.resize(cam.numpy(), (512, 512))

