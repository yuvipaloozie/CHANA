# Data structures for global PR curve cache
pr_pixel_truth = {m: [] for m in df_inference_cache['model_id'].unique()}
pr_pixel_probs = {m: [] for m in df_inference_cache['model_id'].unique()}

for _, row in tqdm(df_inference_cache.iterrows(), total=len(df_inference_cache), desc="Extracting Image Metrics"):
    # Load Truth
    t_mask = cv2.imread(row['mask_path'], cv2.IMREAD_UNCHANGED)
    if t_mask is None: t_mask = io.imread(row['mask_path'])
    t_mask = cv2.resize(t_mask, CONFIG.img_size, interpolation=cv2.INTER_NEAREST)
    if t_mask.ndim > 2: t_mask = t_mask[:,:,0]
    t_bin = (t_mask > 0).astype(np.uint8)

    # Load Prediction
    with np.load(row['prob_cache_path']) as data:
        p_prob = data['prob_map']
    p_bin = ndimage.binary_fill_holes((p_prob > CONFIG.probability_threshold)).astype(np.uint8)

    # Stratified sample for global PR curves
    pr_pixel_truth[row['model_id']].extend(t_bin.flatten()[SAMPLE_INDICES])
    pr_pixel_probs[row['model_id']].extend(p_prob.flatten()[SAMPLE_INDICES])

    # --- PIXEL METRICS ---
    tp = np.sum((t_bin == 1) & (p_bin == 1))
    fp = np.sum((t_bin == 0) & (p_bin == 1))
    fn = np.sum((t_bin == 1) & (p_bin == 0))
    tn = np.sum((t_bin == 0) & (p_bin == 0))

    dice = (2 * tp) / (2 * tp + fp + fn + 1e-6)
    iou = tp / (tp + fp + fn + 1e-6) if (np.sum(t_bin) > 0 or np.sum(p_bin) > 0) else 1.0
    sensitivity = tp / (tp + fn + 1e-6)
    specificity = tn / (tn + fp + 1e-6)
    balanced_acc = (sensitivity + specificity) / 2.0
    prevalence = (tp + fn) / TOTAL_PIXELS

    # Average Precision (AP) for this specific image (Fast on 262k pixels)
    if prevalence > 0:
        ap_score = average_precision_score(t_bin.flatten(), p_prob.flatten())
    else:
        ap_score = np.nan

    # --- EXPLICIT HD95 HANDLING ---
    is_empty_t = (np.sum(t_bin) == 0)
    is_empty_p = (np.sum(p_bin) == 0)

    if is_empty_t and is_empty_p:
        hd_status = 'Empty_Both (Success)'
        hd_finite = 0.0
    elif is_empty_t and not is_empty_p:
        hd_status = 'Empty_Truth (Hallucination Failure)'
        hd_finite = np.nan
    elif not is_empty_t and is_empty_p:
        hd_status = 'Empty_Pred (Miss Failure)'
        hd_finite = np.nan
    else:
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                hd_finite = hd95(p_bin, t_bin, voxelspacing=(1,1))
            hd_status = 'Success'
        except Exception:
            hd_finite = np.nan
            hd_status = 'Compute_Failed'

    metric_row = row.to_dict()
    metric_row.update({
        'Dice': dice,
        'IoU': iou,
        'Sensitivity': sensitivity,
        'Specificity': specificity,
        'Balanced_Accuracy': balanced_acc,
        'Pixel_Prevalence': prevalence,
        'Average_Precision': ap_score,
        'Is_Empty_Truth': is_empty_t,
        'Is_Empty_Prediction': is_empty_p,
        'HD95_Finite': hd_finite,
        'HD95_Status': hd_status
    })
    metrics_list.append(metric_row)

