def phase_object_metrics(truth_binary, prediction_binary):
    _, truth_properties = instances_from_binary(truth_binary)
    _, prediction_properties = instances_from_binary(prediction_binary)
    truth_centroids = np.asarray([region.centroid for region in truth_properties], dtype=float)
    prediction_centroids = np.asarray([region.centroid for region in prediction_properties], dtype=float)
    true_positive = 0
    if len(truth_centroids) and len(prediction_centroids):
        distances = cdist(truth_centroids, prediction_centroids)
        truth_index, prediction_index = linear_sum_assignment(distances)
        true_positive = int(np.sum(distances[truth_index, prediction_index] <= CONFIG.hungarian_match_max_dist))
    false_negative = len(truth_properties) - true_positive
    false_positive = len(prediction_properties) - true_positive
    precision = true_positive / (true_positive + false_positive + 1e-9)
    recall = true_positive / (true_positive + false_negative + 1e-9)
    return {
        "Object_Precision": precision,
        "Object_Recall": recall,
        "Object_F1": 2 * precision * recall / (precision + recall + 1e-9),
        "Count_True": len(truth_properties),
        "Count_Pred": len(prediction_properties),
        "Count_Absolute_Error": abs(len(prediction_properties) - len(truth_properties)),
    }


