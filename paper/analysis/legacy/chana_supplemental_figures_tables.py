def apply_v9_preprocessing_array(rgb: np.ndarray):
    """Apply the documented CIELAB/CLAHE/top-hat transformation."""
    lab = cv2.cvtColor(rgb, cv2.COLOR_RGB2LAB)
    lightness, channel_a, channel_b = cv2.split(lab)
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    lightness_clahe = clahe.apply(lightness)
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (15, 15))
    top_hat = cv2.morphologyEx(lightness_clahe, cv2.MORPH_TOPHAT, kernel)
    fused_lightness = cv2.addWeighted(lightness_clahe, 1.0, top_hat, 0.8, 0)
    fused_rgb = cv2.cvtColor(
        cv2.merge((fused_lightness, channel_a, channel_b)), cv2.COLOR_LAB2RGB
    )
    return lightness, lightness_clahe, top_hat, fused_rgb


