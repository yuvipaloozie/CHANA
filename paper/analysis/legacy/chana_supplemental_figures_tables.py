def bootstrap_ci(
    values: Iterable[float],
    statistic: Callable = np.mean,
    repetitions: Optional[int] = None,
    seed: Optional[int] = None,
    confidence: float = 0.95,
) -> tuple[float, float]:
    """Percentile bootstrap interval for one-dimensional observations."""
    array = np.asarray(list(values), dtype=float)
    array = array[np.isfinite(array)]
    if len(array) < 2:
        return np.nan, np.nan
    repetitions = repetitions or BOOTSTRAP_REPETITIONS
    seed = CONFIG.random_seed if seed is None else seed
    rng = np.random.default_rng(seed)
    estimates = np.empty(repetitions, dtype=float)
    for index in range(repetitions):
        estimates[index] = statistic(rng.choice(array, size=len(array), replace=True))
    alpha = (1 - confidence) / 2
    return tuple(np.quantile(estimates, [alpha, 1 - alpha]))


def bootstrap_bland_altman(
    differences: Iterable[float],
    repetitions: Optional[int] = None,
    seed: Optional[int] = None,
) -> dict:
    """Bootstrap CIs for mean bias and Bland-Altman limits of agreement."""
    values = np.asarray(list(differences), dtype=float)
    values = values[np.isfinite(values)]
    if len(values) < 3:
        return {key: np.nan for key in [
            "bias_ci_lower", "bias_ci_upper", "loa_lower_ci_lower",
            "loa_lower_ci_upper", "loa_upper_ci_lower", "loa_upper_ci_upper"
        ]}
    repetitions = repetitions or BOOTSTRAP_REPETITIONS
    seed = CONFIG.random_seed if seed is None else seed
    rng = np.random.default_rng(seed)
    estimates = []
    for _ in range(repetitions):
        sample = rng.choice(values, size=len(values), replace=True)
        bias = np.mean(sample)
        sd = np.std(sample, ddof=1)
        estimates.append((bias, bias - 1.96 * sd, bias + 1.96 * sd))
    estimates = np.asarray(estimates)
    intervals = np.quantile(estimates, [0.025, 0.975], axis=0)
    return {
        "bias_ci_lower": intervals[0, 0],
        "bias_ci_upper": intervals[1, 0],
        "loa_lower_ci_lower": intervals[0, 1],
        "loa_lower_ci_upper": intervals[1, 1],
        "loa_upper_ci_lower": intervals[0, 2],
        "loa_upper_ci_upper": intervals[1, 2],
    }


def holm_adjust(p_values: Sequence[float]) -> np.ndarray:
    """Holm family-wise error correction without requiring statsmodels."""
    p_values = np.asarray(p_values, dtype=float)
    adjusted = np.full(len(p_values), np.nan)
    finite_positions = np.flatnonzero(np.isfinite(p_values))
    if len(finite_positions) == 0:
        return adjusted
    order = finite_positions[np.argsort(p_values[finite_positions])]
    running_max = 0.0
    number = len(order)
    for rank, original_position in enumerate(order):
        candidate = min(1.0, (number - rank) * p_values[original_position])
        running_max = max(running_max, candidate)
        adjusted[original_position] = running_max
    return adjusted


