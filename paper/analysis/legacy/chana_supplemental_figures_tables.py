def instances_from_binary(binary_mask: np.ndarray, peak_distance: Optional[int] = None):
    """Watershed-derived instances from a semantic binary mask."""
    peak_distance = peak_distance or CONFIG.watershed_peak_distance
    distance = ndimage.distance_transform_edt(binary_mask)
    peaks = peak_local_max(distance, min_distance=peak_distance, labels=binary_mask)
    if len(peaks) == 0:
        labels = measure.label(binary_mask)
    else:
        peak_mask = np.zeros(distance.shape, dtype=bool)
        peak_mask[tuple(peaks.T)] = True
        markers, _ = ndimage.label(peak_mask)
        labels = watershed(-distance, markers, mask=binary_mask)
    properties = [
        region for region in measure.regionprops(labels)
        if CONFIG.min_object_area <= region.area <= CONFIG.max_object_area
    ]
    return labels, properties


