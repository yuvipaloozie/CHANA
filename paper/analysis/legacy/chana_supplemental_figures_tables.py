def segmentation_gradcam(rgb: np.ndarray, model: tf.keras.Model, output_index: int):
    """Gradient activation map for mean foreground probability, not generic attention."""
    output_tensor = model.outputs[output_index] if isinstance(model.output, list) else model.output
    candidate_layers = [
        layer for layer in model.layers
        if isinstance(layer, (tf.keras.layers.Conv2D, tf.keras.layers.Conv2DTranspose))
        and not any(token in layer.name.lower() for token in ["output", "final", "aux"])
    ]
    if not candidate_layers:
        raise RuntimeError("No convolutional layer found for gradient activation mapping.")
    normalized = (rgb.astype(np.float32) / 255.0 - IMAGENET_MEAN) / IMAGENET_STD
    for layer in reversed(candidate_layers):
        try:
            gradient_model = tf.keras.Model(model.inputs, [layer.output, output_tensor])
            with tf.GradientTape() as tape:
                activations, predictions = gradient_model(normalized[None, ...], training=False)
                scalar_target = tf.reduce_mean(predictions[..., 0])
            gradients = tape.gradient(scalar_target, activations)
            if gradients is None:
                continue
            pooled_gradients = tf.reduce_mean(gradients[0], axis=(0, 1))
            activation_map = tf.reduce_sum(activations[0] * pooled_gradients, axis=-1)
            activation_map = tf.maximum(activation_map, 0)
            maximum = tf.reduce_max(activation_map)
            if maximum > 0:
                activation_map = activation_map / maximum
            return cv2.resize(activation_map.numpy(), CONFIG.img_size), layer.name
        except Exception:
            continue
    raise RuntimeError("No connected convolutional layer produced a valid gradient map.")


