def properties_with_settings(binary, peak_distance, maximum_area):
    distance = ndimage.distance_transform_edt(binary)
    peaks = peak_local_max(distance, min_distance=peak_distance, labels=binary)
    if len(peaks):
        peak_mask = np.zeros(distance.shape, dtype=bool)
        peak_mask[tuple(peaks.T)] = True
        markers, _ = ndimage.label(peak_mask)
        labels = watershed(-distance, markers, mask=binary)
    else:
        labels = measure.label(binary)
    return [region for region in measure.regionprops(labels)
            if CONFIG.min_object_area <= region.area <= maximum_area]


for peak_distance, maximum_area, match_distance, varied_parameter in parameter_sets:
    for row in tqdm(primary_rows.itertuples(), total=len(primary_rows), leave=False,
                    desc=f"S14 {varied_parameter}"):
        truth = load_truth_mask(row.mask_path)
        probability = load_probability_map(row.prob_cache_path)
        prediction = ndimage.binary_fill_holes(probability >= CONFIG.probability_threshold)
        truth_properties = properties_with_settings(truth, peak_distance, maximum_area)
        prediction_properties = properties_with_settings(prediction, peak_distance, maximum_area)
        truth_centroids = np.asarray([region.centroid for region in truth_properties], dtype=float)
        prediction_centroids = np.asarray([region.centroid for region in prediction_properties], dtype=float)
        tp = 0
        if len(truth_centroids) and len(prediction_centroids):
            distances = cdist(truth_centroids, prediction_centroids)
            truth_index, prediction_index = linear_sum_assignment(distances)
            tp = int(np.sum(distances[truth_index, prediction_index] <= match_distance))
        fp = len(prediction_properties) - tp
        fn = len(truth_properties) - tp
        precision = tp / (tp + fp + 1e-9)
        recall = tp / (tp + fn + 1e-9)
        sensitivity_rows.append({
            "image_id": row.image_id, "varied_parameter": varied_parameter,
            "watershed_peak_distance": peak_distance, "maximum_object_area": maximum_area,
            "centroid_match_distance": match_distance,
            "Object_F1": 2 * precision * recall / (precision + recall + 1e-9),
            "Count_Absolute_Error": abs(len(prediction_properties) - len(truth_properties)),
        })
