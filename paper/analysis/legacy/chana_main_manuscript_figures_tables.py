def load_native_rgb(path):
    """Load a source image without resizing and return uint8 RGB."""
    image = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    if image is None:
        image = io.imread(str(path))
        if image.ndim == 2:
            image = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
        elif image.shape[-1] == 4:
            image = image[..., :3]
    else:
        if image.ndim == 2:
            image = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
        elif image.shape[-1] == 4:
            image = cv2.cvtColor(image, cv2.COLOR_BGRA2RGB)
        else:
            image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    if image.dtype != np.uint8:
        finite = image[np.isfinite(image)]
        maximum = float(finite.max()) if finite.size else 1.0
        image = np.clip(image / maximum * 255.0, 0, 255).astype(np.uint8)
    return image


def save_native_tiff(array, path, dpi=300):
    """Write LZW-compressed TIFF while retaining the array's pixel dimensions."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    array = np.asarray(array)
    if array.dtype == np.float32 or array.dtype == np.float64:
        tifffile.imwrite(
            path, array.astype(np.float32), compression="deflate",
            resolution=(dpi, dpi), resolutionunit="INCH",
        )
    else:
        Image.fromarray(array).save(path, format="TIFF", compression="tiff_lzw", dpi=(dpi, dpi))
    return path


