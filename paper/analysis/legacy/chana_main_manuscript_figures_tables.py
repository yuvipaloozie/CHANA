def frechet_feature_distance(features_a: np.ndarray, features_b: np.ndarray) -> float:
    """Fréchet distance between Gaussian approximations of two feature sets."""
    mean_a, mean_b = features_a.mean(axis=0), features_b.mean(axis=0)
    covariance_a = np.cov(features_a, rowvar=False)
    covariance_b = np.cov(features_b, rowvar=False)
    covariance_mean = sqrtm(covariance_a @ covariance_b)
    if np.iscomplexobj(covariance_mean):
        covariance_mean = covariance_mean.real
    difference = mean_a - mean_b
    return float(
        difference @ difference + np.trace(covariance_a + covariance_b - 2 * covariance_mean)
    )


def kid_mmd2_unbiased(features_a: np.ndarray, features_b: np.ndarray) -> float:
    """Unbiased polynomial-kernel MMD² (KID-style feature distance)."""
    gamma = 1.0 / features_a.shape[1]
    kernel_aa = polynomial_kernel(features_a, features_a, degree=3, gamma=gamma, coef0=1)
    kernel_bb = polynomial_kernel(features_b, features_b, degree=3, gamma=gamma, coef0=1)
    kernel_ab = polynomial_kernel(features_a, features_b, degree=3, gamma=gamma, coef0=1)
    number_a, number_b = len(features_a), len(features_b)
    term_a = (kernel_aa.sum() - np.trace(kernel_aa)) / (number_a * (number_a - 1))
    term_b = (kernel_bb.sum() - np.trace(kernel_bb)) / (number_b * (number_b - 1))
    return float(term_a + term_b - 2 * kernel_ab.mean())


