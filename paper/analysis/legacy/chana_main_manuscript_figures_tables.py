def load_native_rgb(path):
    """Load an image at its original resolution as uint8 RGB."""
    image = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)

    if image is None:
        image = io.imread(str(path))

        if image.ndim == 2:
            image = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
        elif image.shape[-1] == 4:
            image = image[..., :3]
    else:
        if image.ndim == 2:
            image = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
        elif image.shape[-1] == 4:
            image = cv2.cvtColor(image, cv2.COLOR_BGRA2RGB)
        else:
            image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    if image.dtype != np.uint8:
        finite = image[np.isfinite(image)]
        maximum = float(finite.max()) if finite.size else 1.0

        if maximum <= 0:
            maximum = 1.0

        image = np.clip(
            image.astype(np.float32) / maximum * 255.0,
            0,
            255,
        ).astype(np.uint8)

    return image


def save_native_tiff(array, path, dpi=300):
    """Save a TIFF while retaining the array's native pixel dimensions."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    array = np.asarray(array)

    if array.dtype in (np.float32, np.float64):
        tifffile.imwrite(
            path,
            array.astype(np.float32),
            compression="deflate",
            resolution=(dpi, dpi),
            resolutionunit="INCH",
        )
    else:
        Image.fromarray(array).save(
            path,
            format="TIFF",
            compression="tiff_lzw",
            dpi=(dpi, dpi),
        )

    return path


