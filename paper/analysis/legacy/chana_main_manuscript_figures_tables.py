def cluster_summary_table(frame: pd.DataFrame) -> pd.DataFrame:
    """Aggregate tiles within the prespecified well/analysis unit."""
    rows = []
    for (model_id, unit_id), group in frame.groupby(["model_id", "analysis_unit_id"], sort=True):
        tp = int(group["Object_TP"].sum())
        fp = int(group["Object_FP"].sum())
        fn = int(group["Object_FN"].sum())
        precision = tp / (tp + fp) if tp + fp else (1.0 if fn == 0 else 0.0)
        recall = tp / (tp + fn) if tp + fn else 1.0
        object_f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        rows.append({
            "model_id": model_id,
            "architecture": group["architecture"].iloc[0],
            "training_regime": group["training_regime"].iloc[0],
            "analysis_unit_id": unit_id,
            "n_images": group["image_id"].nunique(),
            "IoU": group["IoU"].mean(),
            "Dice": group["Dice"].mean(),
            "Average_Precision": group["Average_Precision"].mean(),
            "HD95_Finite": group["HD95_Finite"].median(),
            "HD95_Failure_Rate": group["HD95_Failure"].mean(),
            "Object_TP": tp,
            "Object_FP": fp,
            "Object_FN": fn,
            "Object_Precision": precision,
            "Object_Recall": recall,
            "Object_F1": object_f1,
            "Count_MAE": group["Count_Error_Absolute"].mean(),
            "Count_Bias": group["Count_Error_Signed"].mean(),
        })
    return pd.DataFrame(rows)


