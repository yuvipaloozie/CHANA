# --- HELPER: SHAPE GUARD (FIXED) ---
def filter_mask_by_shape(binary_mask, min_circ=0.5):
    """Removes jagged/irregular objects from the binary mask."""
    # SQUEEZE IS CRITICAL HERE
    binary_mask = np.squeeze(binary_mask)

    labeled = measure.label(binary_mask)
    cleaned = np.zeros_like(binary_mask)

    for region in measure.regionprops(labeled):
        if region.area < 100: continue
        if region.perimeter == 0: continue

        circularity = (4 * math.pi * region.area) / (region.perimeter ** 2)

        if circularity >= min_circ:
            coords = region.coords
            cleaned[coords[:, 0], coords[:, 1]] = 255

    return cleaned

# --- EXECUTION ---
