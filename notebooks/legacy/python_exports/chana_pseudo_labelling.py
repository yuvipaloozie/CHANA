    try:
        # Preprocess
        img_path = os.path.join(UNLABELED_DIR, f)
        img = cv2.imread(img_path)
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        img_raw = cv2.resize(img, (512, 512), interpolation=cv2.INTER_AREA) # Keep for saving

        # Normalize for Model
        norm_img = img_raw.astype(np.float32) / 255.0
        norm_img = (norm_img - IMAGENET_MEAN) / IMAGENET_STD

        # Predict
        pred_prob = model.predict(np.expand_dims(norm_img, 0), verbose=0)[0][0] # (512, 512, 1)

        # --- CALCULATE CONFIDENCE ---
        # Metric: Mean probability of pixels that the model "thinks" are cells (>0.5)
        # If the model finds nothing, confidence is 0.
        cell_pixels = pred_prob[pred_prob > 0.5]

        if cell_pixels.size > 0:
            conf = np.mean(cell_pixels)
        else:
            conf = 0.0

        confidence_scores.append(conf)

        # Cache (Compress mask to uint8 to save RAM: 0-255)
        # We only cache if conf > 0.5 to save memory (totally empty images are useless anyway)
        if conf > 0.5:
            cached_predictions.append({
                'filename': f,
                'confidence': conf,
                'pred_prob': (pred_prob * 255).astype(np.uint8), # Store as uint8 0-255
                'img_raw': img_raw
            })

    except Exception as e:
        print(f"Error on {f}: {e}")

    if i % 100 == 0: print(f"   Processed {i}/{len(files)}...")

