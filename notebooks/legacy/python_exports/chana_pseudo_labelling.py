    if item['confidence'] >= FINAL_THRESHOLD:

        # Prepare Raw Mask
        prob_map = item['pred_prob'].astype(np.float32) / 255.0
        # Create binary (0 or 1) and ensure 2D
        raw_mask = np.squeeze((prob_map > 0.5).astype(np.uint8))

        # Filter
        final_mask = filter_mask_by_shape(raw_mask, min_circ=MIN_CIRCULARITY)

