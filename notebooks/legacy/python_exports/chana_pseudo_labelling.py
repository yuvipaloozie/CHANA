total_objects = 0

for item in cached_predictions:
    # Get Binary Mask
    prob_map = item['pred_prob'].astype(np.float32) / 255.0

    # --- FIX: SQUEEZE TO ENSURE 2D (512, 512) ---
    # The error happened because it was (512, 512, 1)
    mask = np.squeeze((prob_map > 0.5).astype(np.uint8))

    labeled = measure.label(mask)
    regions = measure.regionprops(labeled)

    # Check this image against multiple thresholds
    max_circ_in_image = 0

    for r in regions:
        if r.area < 100: continue # Ignore specks
        if r.perimeter == 0: continue

        circ = (4 * math.pi * r.area) / (r.perimeter ** 2)
        all_circularities.append(circ)
        total_objects += 1

        if circ > max_circ_in_image:
            max_circ_in_image = circ

    # Track "Image Survival Rate"
    for t in images_kept_at_threshold.keys():
        if max_circ_in_image >= t:
            images_kept_at_threshold[t] += 1

