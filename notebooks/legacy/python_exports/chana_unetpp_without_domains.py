    def make_gradcam(img_tensor, model, layer_name):
        # --- GRAD-CAM FIX FOR DEEP SUPERVISION ---
        # Explicitly target model.outputs[0] (the main output)
        primary_output = model.outputs[0] if isinstance(model.outputs, list) else model.output

        grad_model = Model([model.inputs], [model.get_layer(layer_name).output, primary_output])

        with tf.GradientTape() as tape:
            conv_outputs, predictions = grad_model(img_tensor)
            # predictions shape: (Batch, H, W, Channels). We want channel 0.
            loss = predictions[:, :, :, 0]

        output = conv_outputs[0]
        grads = tape.gradient(loss, conv_outputs)[0]

        weights = tf.reduce_mean(grads, axis=(0, 1))
        cam = tf.reduce_sum(tf.multiply(weights, output), axis=-1)

        cam = tf.maximum(cam, 0) # ReLU
        cam = cam / (tf.reduce_max(cam) + 1e-6) # Normalize
        cam = cam.numpy()
        cam = cv2.resize(cam, (512, 512))
        return cam

