import tensorflow.keras.backend as K

# Strategy 1: "Robust" (Focal Tversky) - For Trusted Labels
def focal_tversky_loss(y_true, y_pred, alpha=0.3, beta=0.7, gamma=1.5):
    y_true_f = K.flatten(y_true)
    y_pred_f = K.flatten(y_pred)
    tp = K.sum(y_true_f * y_pred_f)
    fn = K.sum(y_true_f * (1 - y_pred_f))
    fp = K.sum((1 - y_true_f) * y_pred_f)
    tversky = (tp + 1e-6) / (tp + alpha * fn + beta * fp + 1e-6)
    return K.pow((1 - tversky), gamma)

# Strategy 2: "Soft" (BCE + Label Smoothing) - For Noisy Labels/Arrogant Models
def soft_bce_loss(y_true, y_pred):
    # Standard BCE with label smoothing (0.1 means target becomes 0.95/0.05)
    return tf.keras.losses.binary_crossentropy(y_true, y_pred, label_smoothing=0.1)

def dice_loss_fn(y_true, y_pred):
    smooth = 1e-6
    intersection = K.sum(y_true * y_pred)
    return 1 - (2. * intersection + smooth) / (K.sum(y_true) + K.sum(y_pred) + smooth)

