    with tf.GradientTape() as tape:
        conv_outputs, predictions = grad_model(img_tensor)
        # Handle list vs tensor just in case
        if isinstance(predictions, list): predictions = predictions[-1]

        loss = predictions[:, :, :, 0]

    grads = tape.gradient(loss, conv_outputs)
    if grads is None: return np.zeros((512,512)) # Safety

    grads = grads[0]
    weights = tf.reduce_mean(grads, axis=(0, 1))
    cam = tf.reduce_sum(tf.multiply(weights, conv_outputs[0]), axis=-1)
    cam = tf.maximum(cam, 0)
    cam = cam / (tf.reduce_max(cam) + 1e-6)
    return cv2.resize(cam.numpy(), (512, 512))

