from tensorflow.keras.applications import DenseNet121

def build_custom_unet(input_shape, num_classes):
    print(f"🏗️ Building Native Standard U-Net (DenseNet121)...")

    # 1. INPUT
    inputs = Input(shape=input_shape, name='input_layer')

    # 2. BACKBONE (Encoder)
    encoder = DenseNet121(include_top=False, weights='imagenet', input_tensor=inputs)
    encoder.trainable = True

    # --- HELPER: ROBUST LAYER EXTRACTOR ---
    def get_layer_output(model, name_options):
        """Tries to find a layer matching one of the names in the list."""
        for name in name_options:
            try:
                return model.get_layer(name).output
            except ValueError:
                continue
        # If we get here, none matched. Print available layers for debugging.
        print(f"❌ Critical Error: Could not find layer. Tried: {name_options}")
        raise ValueError(f"Could not find any valid layer name in {name_options}")

    # 3. SKIP CONNECTIONS (Checking both Slash and Underscore names)
    # --------------------------------------------------------------------------
    # Level 1: 256x256
    s1 = get_layer_output(encoder, ['conv1/relu', 'conv1_relu'])

    # Level 2: 128x128
    s2 = get_layer_output(encoder, ['conv2_block6_concat', 'conv2/block6/concat'])

    # Level 3: 64x64
    s3 = get_layer_output(encoder, ['conv3_block12_concat', 'conv3/block12/concat'])

    # Level 4: 32x32
    s4 = get_layer_output(encoder, ['conv4_block24_concat', 'conv4/block24/concat'])

    # Bridge: 16x16
    bridge = get_layer_output(encoder, ['conv5_block16_concat', 'conv5/block16/concat'])
    # --------------------------------------------------------------------------

    # 4. DECODER
    def decoder_block(input_tensor, skip_tensor, filters):
        x = layers.Conv2DTranspose(filters, (2, 2), strides=(2, 2), padding='same')(input_tensor)
        x = layers.Concatenate()([x, skip_tensor])
        x = layers.Conv2D(filters, (3, 3), padding='same', activation='relu')(x)
        x = layers.Conv2D(filters, (3, 3), padding='same', activation='relu')(x)
        return x

    d1 = decoder_block(bridge, s4, 512)
    d2 = decoder_block(d1, s3, 256)
    d3 = decoder_block(d2, s2, 128)
    d4 = decoder_block(d3, s1, 64)

    # Final Upsample
    d5 = layers.Conv2DTranspose(32, (2, 2), strides=(2, 2), padding='same')(d4)
    d5 = layers.Conv2D(32, (3, 3), padding='same', activation='relu')(d5)

    # 5. OUTPUT HEAD (Standard Single Output)
    outputs = layers.Conv2D(num_classes, (1, 1), activation='sigmoid', name='final_output', dtype='float32')(d5)

    final_model = Model(inputs=inputs, outputs=outputs, name="Standard_DenseNet_UNet")

    print(f"✅ Architecture Ready: Standard U-Net (DenseNet121)")
    print(f"   -> Outputs: 1 (Standard)")

    return final_model

