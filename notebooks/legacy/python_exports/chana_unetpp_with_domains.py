def augment_data(img, mask):
    aug = aug_pipeline(image=img, mask=mask)
    return aug['image'], aug['mask']

def load_and_process(img_path, mask_path):
    path_str = img_path.decode('utf-8')
    try:
        img = cv2.imread(path_str, cv2.IMREAD_COLOR)
        if img is None: # Fallback for TIF/Special formats
            img = io.imread(path_str)
            if img.ndim == 2: img = cv2.cvtColor(img, cv2.COLOR_GRAY2RGB)
            elif img.shape[2] == 4: img = img[:,:,:3]
    except:
        return np.zeros((512,512,3), dtype=np.float32), np.zeros((512,512,1), dtype=np.float32)

    if img is not None:
        if path_str.lower().endswith(('.png', '.jpg')):
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    img = cv2.resize(img, (512, 512), interpolation=cv2.INTER_AREA)
    img = preprocess_input_v7(img)

    m_path_str = mask_path.decode('utf-8')
    if m_path_str.endswith('.tif'): mask = io.imread(m_path_str)
    else: mask = cv2.imread(m_path_str, cv2.IMREAD_GRAYSCALE)
    if mask is None: mask = io.imread(m_path_str)

    if mask.shape[:2] != (512, 512):
        mask = cv2.resize(mask, (512, 512), interpolation=cv2.INTER_NEAREST)

    mask = (mask > 0).astype(np.float32)
    if mask.ndim == 2: mask = np.expand_dims(mask, axis=-1)

    return img, mask

def create_tf_dataset(images, masks, training=True):
    ds = tf.data.Dataset.from_tensor_slices((images, masks))
    ds = ds.shuffle(len(images)) if training else ds
    ds = ds.repeat()

    ds = ds.map(lambda i, m: tf.numpy_function(load_and_process, [i, m], [tf.float32, tf.float32]),
                num_parallel_calls=tf.data.AUTOTUNE)

    if training:
        ds = ds.map(lambda i, m: tf.numpy_function(augment_data, [i, m], [tf.float32, tf.float32]),
                    num_parallel_calls=tf.data.AUTOTUNE)

    # UPDATED FOR TRUE DEEP SUPERVISION (4 Outputs, All Full Res)
    def format_output(i, m):
        i = tf.ensure_shape(i, [512, 512, 3])
        m = tf.ensure_shape(m, [512, 512, 1])
        # UNet++ (depth 4) with deep supervision produces 4 outputs at level 0.
        # All of them are 512x512. We just replicate the mask.
        return i, (m, m, m, m)

    ds = ds.map(format_output, num_parallel_calls=tf.data.AUTOTUNE)
    ds = ds.batch(BATCH_SIZE).prefetch(tf.data.AUTOTUNE)
    return ds

