# 2. GRAD-CAM FUNCTION
def make_gradcam(img_tensor, model, layer_name):
    # Map input to (Target Layer Output, Final Prediction)
    grad_model = Model(model.inputs, [model.get_layer(layer_name).output, model.output[-1]])

    with tf.GradientTape() as tape:
        conv_outputs, predictions = grad_model(img_tensor)
        # Handle predictions being a list or tensor
        if isinstance(predictions, list):
            loss = predictions[-1][:, :, :, 0]
        else:
            loss = predictions[:, :, :, 0]

    grads = tape.gradient(loss, conv_outputs)

    # Safety Check: If layer is disconnected, grads will be None
    if grads is None:
        raise ValueError(f"Gradient is None. Layer '{layer_name}' is disconnected from output.")

    grads = grads[0] # Get the gradient tensor

    # Global Average Pooling of gradients
    weights = tf.reduce_mean(grads, axis=(0, 1))

    # Weight the feature maps
    cam = tf.reduce_sum(tf.multiply(weights, conv_outputs[0]), axis=-1)

    # ReLU and Normalize
    cam = tf.maximum(cam, 0)
    cam = cam / (tf.reduce_max(cam) + 1e-6)

    # Resize to image size
    cam = cam.numpy()
    cam = cv2.resize(cam, (512, 512))
    return cam

