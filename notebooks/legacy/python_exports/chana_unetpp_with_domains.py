def load_and_process(img_path, mask_path):
    # 1. ROBUST INPUT HANDLING (Bytes vs String)
    # The resurrection script passes strings, but training passed bytes.
    # We handle both here to prevent variable errors.
    if isinstance(img_path, bytes):
        path_str = img_path.decode('utf-8')
    else:
        path_str = img_path

    if isinstance(mask_path, bytes):
        m_path_str = mask_path.decode('utf-8')
    else:
        m_path_str = mask_path

    # 2. LOAD IMAGE
    try:
        img = cv2.imread(path_str, cv2.IMREAD_COLOR)
        # Fallback for TIF or if cv2 fails
        if img is None:
            img = io.imread(path_str)

        # Color Conversion
        if img is not None:
            if img.ndim == 2: # Grayscale -> RGB
                img = cv2.cvtColor(img, cv2.COLOR_GRAY2RGB)
            elif img.shape[2] == 4: # RGBA -> RGB
                img = img[:,:,:3]
            elif path_str.lower().endswith(('.png', '.jpg')) and img.ndim == 3: # BGR -> RGB
                # cv2 loads JPG/PNG as BGR by default
                img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        img = cv2.resize(img, (512, 512), interpolation=cv2.INTER_AREA)
        img = preprocess_input_v7(img)

    except Exception as e:
        # Return zeros if image load fails
        return np.zeros((512,512,3), np.float32), np.zeros((512,512,1), np.float32)

    # 3. LOAD MASK
    try:
        # Check extension using the SAFELY defined m_path_str
        if m_path_str.endswith('.tif'):
            mask = io.imread(m_path_str)
        else:
            mask = cv2.imread(m_path_str, cv2.IMREAD_GRAYSCALE)

        if mask is None:
            mask = io.imread(m_path_str)

        if mask.shape[:2] != (512, 512):
            mask = cv2.resize(mask, (512, 512), interpolation=cv2.INTER_NEAREST)

        mask = (mask > 0).astype(np.float32)
        if mask.ndim == 2:
            mask = np.expand_dims(mask, axis=-1)

    except Exception as e:
        # Return zeros if mask load fails
        return np.zeros((512,512,3), np.float32), np.zeros((512,512,1), np.float32)

    return img, mask

