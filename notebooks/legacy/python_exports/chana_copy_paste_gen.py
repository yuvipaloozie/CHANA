# Parameters
MIN_CELL_AREA = 150  # Filter out noise/debris
SKIP_BG_RATE = 3     # Only grab background from every 3rd image (avoid bloat)

def harvest_assets():
    print(f"🚜 STARTING HARVEST from {INPUT_IMG_DIR}...")

    # Gather pairs
    pairs = []
    for f in os.listdir(INPUT_IMG_DIR):
        base = os.path.splitext(f)[0]
        # Robust mask matching
        candidates = [base + '_mask.png', base + '_mask.tif', base + '.png', base + '.tif']
        found_mask = None
        for c in candidates:
            if os.path.exists(os.path.join(INPUT_MASK_DIR, c)):
                found_mask = os.path.join(INPUT_MASK_DIR, c); break

        if found_mask:
            pairs.append((os.path.join(INPUT_IMG_DIR, f), found_mask))

    print(f"   -> Found {len(pairs)} valid image/mask pairs.")

    cell_count = 0
    bg_count = 0

    for i, (img_path, mask_path) in enumerate(tqdm(pairs, desc="Harvesting")):
        # Read
        try:
            img = cv2.imread(img_path); img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
            mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
            if mask is None: mask = io.imread(mask_path)
        except: continue

        # Resize mask if needed
        if mask.shape[:2] != img.shape[:2]:
            mask = cv2.resize(mask, (img.shape[1], img.shape[0]), interpolation=cv2.INTER_NEAREST)

        mask_bin = (mask > 0).astype(np.uint8)

        # A. Extract Cells
        labels = measure.label(mask_bin)
        for region in measure.regionprops(labels):
            if region.area < MIN_CELL_AREA: continue

            # Expand bbox slightly for context
            minr, minc, maxr, maxc = region.bbox
            h, w = mask_bin.shape
            minr = max(0, minr-4); minc = max(0, minc-4)
            maxr = min(h, maxr+4); maxc = min(w, maxc+4)

            cell_chip = img[minr:maxr, minc:maxc]
            local_mask = (labels[minr:maxr, minc:maxc] == region.label).astype(np.uint8) * 255

            # Save
            cv2.imwrite(os.path.join(CELL_BANK, f"cell_{cell_count}.png"), cv2.cvtColor(cell_chip, cv2.COLOR_RGB2BGR))
            cv2.imwrite(os.path.join(CELL_BANK, f"cell_{cell_count}_mask.png"), local_mask)
            cell_count += 1

        # B. Extract Backgrounds (every Nth image)
        if i % SKIP_BG_RATE == 0:
            step = 512
            h, w = mask_bin.shape
            for y in range(0, h - step + 1, 256):
                for x in range(0, w - step + 1, 256):
                    patch_mask = mask_bin[y:y+step, x:x+step]
                    # Must be empty AND not black padding
                    if np.sum(patch_mask) == 0:
                        patch_img = img[y:y+step, x:x+step]
                        if patch_img.mean() > 40: # Not black
                            cv2.imwrite(os.path.join(BG_BANK, f"bg_{bg_count}.png"), cv2.cvtColor(patch_img, cv2.COLOR_RGB2BGR))
                            bg_count += 1

    print(f"✅ HARVEST COMPLETE.")
    print(f"   - Osteoclasts: {cell_count}")
    print(f"   - Backgrounds: {bg_count}")

    if cell_count < 50:
        raise ValueError("❌ CRITICAL: Too few cells extracted. Check your masks!")

harvest_assets()

