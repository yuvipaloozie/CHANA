# --- FAST COPY WORKER ---
def fast_copy(file_pair):
    src, dst = file_pair
    if not os.path.exists(dst):
        try:
            shutil.copy2(src, dst)
        except Exception as e:
            pass # Skip errors, we have plenty of other files

def load_subset_assets():
    print("🚀 STARTING SMART SUBSET LOAD...")

    # 1. Setup Local Dirs
    for d in [LOCAL_CELL_BANK, LOCAL_BG_BANK]:
        if os.path.exists(d): shutil.rmtree(d)
        os.makedirs(d, exist_ok=True)

    # 2. List & Sample Cells
    print("   Scanning Drive for Cells...", end="")
    all_cells = [f for f in os.listdir(DRIVE_CELL_BANK) if f.endswith('.png') and '_mask' not in f]
    print(f" Found {len(all_cells)} total.")

    # Pick random subset
    selected_cells = random.sample(all_cells, min(len(all_cells), SAMPLE_SIZE_CELLS))

    # Prepare Copy Tasks (Image + Mask)
    cell_tasks = []
    for f in selected_cells:
        # Image
        cell_tasks.append((os.path.join(DRIVE_CELL_BANK, f), os.path.join(LOCAL_CELL_BANK, f)))
        # Mask
        mask_name = f.replace('.png', '_mask.png')
        cell_tasks.append((os.path.join(DRIVE_CELL_BANK, mask_name), os.path.join(LOCAL_CELL_BANK, mask_name)))

    # 3. List & Sample Backgrounds
    print("   Scanning Drive for Backgrounds...", end="")
    all_bgs = [f for f in os.listdir(DRIVE_BG_BANK) if f.endswith('.png')]
    print(f" Found {len(all_bgs)} total.")

    selected_bgs = random.sample(all_bgs, min(len(all_bgs), SAMPLE_SIZE_BG))

    bg_tasks = []
    for f in selected_bgs:
        bg_tasks.append((os.path.join(DRIVE_BG_BANK, f), os.path.join(LOCAL_BG_BANK, f)))

    # 4. Execute Transfer
    total_files = len(cell_tasks) + len(bg_tasks)
    print(f"⚡ Transferring {total_files} files (Subset) to Local SSD...")

    all_tasks = cell_tasks + bg_tasks

    # Use 8 workers (safer for CPU runtime than 16)
    with ThreadPoolExecutor(max_workers=8) as executor:
        list(tqdm(executor.map(fast_copy, all_tasks), total=total_files, desc="Copying"))

    print("✅ SUBSET LOADED. Ready for Generation.")

