def generate_synthetic_data_v2(num_images):
    print(f"🧪 GENERATING {num_images} SYNTHETIC IMAGES...")

    # Load file lists
    cell_files = [f for f in os.listdir(CELL_BANK) if f.endswith('.png') and '_mask' not in f]
    bg_files = [f for f in os.listdir(BG_BANK) if f.endswith('.png')]

    stats = {'success': 0, 'overlap_fail': 0, 'load_fail': 0}

    for i in tqdm(range(num_images), desc="Synthesizing"):
        # Retry loop for this specific image slot
        attempts = 0
        created = False

        while not created and attempts < 10:
            attempts += 1

            # 1. Base Canvas
            bg_name = random.choice(bg_files)
            bg = cv2.imread(os.path.join(BG_BANK, bg_name))
            bg = cv2.resize(bg, (512, 512))
            final_mask = np.zeros((512, 512), dtype=np.uint8)

            # 2. Add Cells
            num_cells = random.randint(CELLS_PER_IMG[0], CELLS_PER_IMG[1])
            placed_count = 0

            for _ in range(num_cells):
                # Pick random cell
                c_name = random.choice(cell_files)
                c_img = cv2.imread(os.path.join(CELL_BANK, c_name))
                c_mask = cv2.imread(os.path.join(CELL_BANK, c_name.replace('.png', '_mask.png')), cv2.IMREAD_GRAYSCALE)

                if c_img is None or c_mask is None: continue

                # Augmentations (Rotate/Flip/Scale)
                scale = random.uniform(0.7, 1.2)
                c_img = cv2.resize(c_img, (0,0), fx=scale, fy=scale)
                c_mask = cv2.resize(c_mask, (0,0), fx=scale, fy=scale, interpolation=cv2.INTER_NEAREST)

                if random.random() > 0.5:
                    c_img = cv2.flip(c_img, 1); c_mask = cv2.flip(c_mask, 1)

                # Check Size
                h, w = c_img.shape[:2]
                if h >= 512 or w >= 512: continue

                # Random Position
                y = random.randint(0, 512 - h)
                x = random.randint(0, 512 - w)

                # Strict Overlap Check
                existing_roi = final_mask[y:y+h, x:x+w]
                intersect = np.logical_and(existing_roi > 0, c_mask > 0).sum()
                if intersect > (0.2 * np.sum(c_mask > 0)): # Allow max 20% overlap
                    stats['overlap_fail'] += 1
                    continue

                # 3. Gaussian Blending (No jagged edges)
                roi_bg = bg[y:y+h, x:x+w]
                alpha = c_mask.astype(float) / 255.0
                alpha = cv2.GaussianBlur(alpha, (3,3), 0) # Smooth edge
                alpha_3 = np.stack([alpha]*3, axis=2)

                blended = (c_img * alpha_3) + (roi_bg * (1.0 - alpha_3))
                bg[y:y+h, x:x+w] = blended.astype(np.uint8)

                # Update Mask
                final_mask[y:y+h, x:x+w] = np.maximum(final_mask[y:y+h, x:x+w], c_mask)
                placed_count += 1

            if placed_count > 0:
                # Save
                fname = f"syn_v7_{i}"
                cv2.imwrite(os.path.join(OUTPUT_LOCAL_IMG, f"{fname}.png"), bg)
                cv2.imwrite(os.path.join(OUTPUT_LOCAL_MASK, f"{fname}_mask.png"), final_mask)
                stats['success'] += 1
                created = True

    print(f"\n✅ GENERATION FINISHED.")
    print(f"   - Created: {stats['success']} images")
    print(f"   - Overlaps Avoided: {stats['overlap_fail']}")

