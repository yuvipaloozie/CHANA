def fast_upload(file_info):
    src_path, dst_path = file_info
    # Only copy if it doesn't exist (or overwrite if you prefer)
    if not os.path.exists(dst_path):
        shutil.copy2(src_path, dst_path)

def upload_folder_multithreaded(local_folder, drive_folder, desc="Uploading"):
    if not os.path.exists(local_folder):
        print(f"⚠️ Warning: Local folder {local_folder} is empty or missing.")
        return

    # 1. Prepare List of Tasks
    files = [f for f in os.listdir(local_folder) if f.endswith(('.png', '.jpg'))]
    tasks = []

    for f in files:
        src = os.path.join(local_folder, f)
        dst = os.path.join(drive_folder, f)
        tasks.append((src, dst))

    if len(tasks) == 0:
        print(f"   No files found in {local_folder}.")
        return

    # 2. Execute with 16 Threads
    print(f"🚀 Turbo-Uploading {len(tasks)} files to {desc}...")

    with ThreadPoolExecutor(max_workers=16) as executor:
        list(tqdm(executor.map(fast_upload, tasks), total=len(tasks), desc=desc))

